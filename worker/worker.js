/**
 * 跑一次分析。worker 与 dev-server 共用这一条路径。
 * @returns {{状态码:number, 对象:object, 日志:object}}
 */
export async function 分析请求({
  body,
  env = {},
  clientIp = "unknown",
  limiter = null,
  fetchImpl = fetch,
  上限 = 默认上限,
}) {
  const 日志 = {
    模态: null,
    输入长度: 0,
    结果: "",
    修复次数: 0,
    上游耗时毫秒: null,
    上游模型: null,
    用量: null,
  };

  if (limiter && !limiter.取(clientIp)) {
    return {
      状态码: 429,
      对象: {
        状态: "拒绝",
        错误: {
          标记: "RATE_LIMITED",
          说明: `同一来源每 ${Math.round(limiter.窗口毫秒 / 1000)} 秒最多 ${limiter.上限} 次，请稍后再发。`,
        },
      },
      日志: { ...日志, 结果: "限流" },
    };
  }

  const 检查 = 检查请求(body, 上限);
  日志.模态 = 检查.模态 || null;
  日志.输入长度 = typeof body?.内容 === "string" ? body.内容.length : 0;
  if (检查.转写来源) 日志.转写来源 = 检查.转写来源;

  if (!检查.通过) {
    日志.结果 = 检查.标记;
    const 是语音 = 检查.标记 === "AUDIO_NOT_IMPLEMENTED";
    return {
      状态码: 检查.状态码,
      对象: {
        状态: 是语音 ? "未实现" : "拒绝",
        错误: { 标记: 检查.标记, 说明: 检查.说明 },
        meta: 检查.模态
          ? { 模态: 检查.模态, 证据单位: 证据单位[检查.模态] }
          : null,
        判定: null,
        提示: 是语音
          ? "语音入口保留，真实语音识别为后续开发。本服务不返回转写结果，也不做假的转写。"
          : "请求没有被处理，所以没有判定。",
      },
      日志,
    };
  }

  const 密钥 = env?.DEEPSEEK_API_KEY;
  if (typeof 密钥 !== "string" || 密钥.trim() === "") {
    日志.结果 = "NO_API_KEY";
    return {
      状态码: 503,
      对象: {
        状态: "降级",
        错误: {
          标记: "NO_API_KEY",
          说明: "服务端没有读到 DEEPSEEK_API_KEY，本次不调用模型，也不给判定。",
        },
        meta: { 模态: 检查.模态, 证据单位: 证据单位[检查.模态] },
        判定: null,
        策略: null,
        溯源: [],
        提示: "出口未配置密钥。可以改用离线演示样例。",
      },
      日志,
    };
  }

  const 超时毫秒 =
    Number(env.UPSTREAM_TIMEOUT_MS) > 0
      ? Number(env.UPSTREAM_TIMEOUT_MS)
      : 上限.上游超时毫秒;
  const 调用 = (追加) =>
    调上游({
      模态: 检查.模态,
      内容: 检查.内容,
      密钥,
      env,
      fetchImpl,
      超时毫秒,
      追加,
    });

  let 上游 = await 带重试(() => 调用());
  日志.上游耗时毫秒 = 上游.耗时;
  if (!上游.通过) {
    日志.结果 = 上游.标记;
    return {
      状态码: 上游.标记 === "UPSTREAM_TIMEOUT" ? 504 : 502,
      对象: 降级对象({
        模态: 检查.模态,
        标记: 上游.标记,
        说明: 上游.说明,
        上游状态: 上游.上游状态,
        原始返回片段: 上游.原文片段,
        修复次数: 0,
      }),
      日志,
    };
  }
  日志.上游模型 = 上游.模型;
  日志.用量 = 上游.用量;

  let 原文 = 上游.正文;
  if (!原文.trim()) {
    日志.结果 = "EMPTY_CONTENT_FROM_MODEL";
    return {
      状态码: 502,
      对象: 降级对象({
        模态: 检查.模态,
        标记: "EMPTY_CONTENT_FROM_MODEL",
        说明: `上游只返回了推理内容，没有返回正文（结束原因=${String(上游.结束原因)}，推理字符数=${上游.推理长度}）。可以调大 MAX_OUTPUT_TOKENS 后重试。`,
        上游状态: 200,
        修复次数: 0,
      }),
      日志,
    };
  }

  const 解析并校验 = (文本) => {
    let 对象 = null;
    let 问题 = [];
    try {
      对象 = JSON.parse(取JSON文本(文本));
    } catch (e) {
      问题 = [`返回内容不是合法 JSON：${String(e?.message || e)}`];
    }
    if (对象 !== null) {
      const 校验 = 校验结果(对象);
      if (!校验.valid) {
        问题 = 校验.errors;
        对象 = null;
      }
    }
    // 契约之外的结构约束（§4.2 / §9.1 / §9.2 / §12）：不降级，只回灌一次让模型自己改。
    const 形态问题 = 对象 === null ? [] : 查策略形态(对象);
    return { 对象, 问题, 形态问题 };
  };

  /* §11 验收 7：出门前把高风险结果的官方出口行补齐（只写 12315 / 96110）。 */
  const 收尾 = () => {
    const 补 = 补齐官方出口(结果.对象);
    if (补) 日志.官方出口 = { 已补齐: true, ...补 };
  };

  let 结果 = 解析并校验(原文);

  if (结果.对象 !== null && 结果.形态问题.length) {
    // 形态回灌：一次。分析本身可用，所以修不好也不降级，只在 日志.形态检查 里记着。
    const 首调用 = {
      耗时毫秒: 日志.上游耗时毫秒,
      模型: 日志.上游模型,
      用量: 日志.用量,
    };
    日志.形态检查 = 结果.形态问题.slice(0, 8);
    const 修 = await 带重试(() =>
      调用([
        { role: "assistant", content: 取JSON文本(原文) },
        { role: "user", content: 形态修复指令(结果.形态问题) },
      ]),
    );
    if (修.通过 && String(修.正文 || "").trim()) {
      const 二 = 解析并校验(修.正文);
      if (二.对象 !== null) {
        日志.修复次数 = (日志.修复次数 || 0) + 1;
        日志.上游耗时毫秒 = (日志.上游耗时毫秒 || 0) + (修.耗时 || 0);
        日志.上游模型 = 修.模型 ?? 日志.上游模型;
        日志.用量 = 修.用量 ?? 日志.用量;
        日志.首调用 = 首调用;
        日志.形态检查 = 二.形态问题.length
          ? 二.形态问题.slice(0, 8)
          : "已按 §4.2 / §9.1 / §9.2 修好";
        结果 = 二;
        原文 = 修.正文;
      } else {
        日志.形态检查 = [
          ...结果.形态问题.slice(0, 8),
          "回避形态的回灌没有过契约校验，保留第一次的结果",
        ];
      }
    } else {
      日志.形态检查 = [
        ...结果.形态问题.slice(0, 8),
        `回避形态的回灌没取回正文：${修.说明 || 修.标记 || "未知"}`,
      ];
    }
  }

  if (结果.对象 === null) {
    // 修复重试：一次。把错误回灌给模型。
    const 首调用 = {
      耗时毫秒: 日志.上游耗时毫秒,
      模型: 日志.上游模型,
      用量: 日志.用量,
    };
    日志.修复次数 = 1;
    上游 = await 带重试(() =>
      调用([
        { role: "assistant", content: 取JSON文本(原文) },
        { role: "user", content: 修复指令(结果.问题) },
      ]),
    );
    日志.上游耗时毫秒 = (日志.上游耗时毫秒 || 0) + (上游.耗时 || 0);
    if (!上游.通过) {
      日志.结果 = `修复失败_${上游.标记}`;
      return {
        状态码: 上游.标记 === "UPSTREAM_TIMEOUT" ? 504 : 502,
        对象: 降级对象({
          模态: 检查.模态,
          标记: `修复失败_${上游.标记}`,
          说明: `第一次返回不合契约，修复重试时上游又报错：${上游.说明}`,
          上游状态: 上游.上游状态,
          校验错误: 结果.问题,
          原始返回片段: 上游.原文片段,
          修复次数: 1,
        }),
        日志,
      };
    }
    原文 = 上游.正文;
    日志.上游模型 = 上游.模型 ?? 日志.上游模型;
    日志.用量 = 上游.用量 ?? 日志.用量;
    日志.首调用 = 首调用;
    结果 = 解析并校验(原文);
    if (结果.对象 === null) {
      日志.结果 = "DEGRADED_INVALID_OUTPUT";
      return {
        状态码: 502,
        对象: 降级对象({
          模态: 检查.模态,
          标记: "DEGRADED_INVALID_OUTPUT",
          说明: "第一次与修复重试都没有通过契约校验，本次不给判定。",
          上游状态: 200,
          校验错误: 结果.问题,
          原始返回片段: 原文,
          修复次数: 1,
        }),
        日志,
      };
    }
    日志.结果 = "成功（修复后）";
    收尾();
    return { 状态码: 200, 对象: 结果.对象, 日志, 原始: 原文 };
  }

  日志.结果 = "成功";
  收尾();
  return { 状态码: 200, 对象: 结果.对象, 日志, 原始: 原文 };
}

/* ===== 限流（按来源，内存计数） =====
 * 说明：内存计数只在同一个 isolate 内有效，属于尽力而为的护栏（执行指令 §10.4 的 API 成本一条）。
 * 要跨实例严格限流得用 Durable Object 或 KV，本原型阶段不做。 */

export function 造限流器({
  上限 = 默认上限.每分钟请求数,
  窗口毫秒 = 默认上限.限流窗口毫秒,
} = {}) {
  const 表 = new Map();
  return {
    上限,
    窗口毫秒,
    取(who) {
      const 键 = String(who || "unknown");
      const 现在 = Date.now();
      const 记 = 表.get(键);
      if (!记 || 现在 - 记.起点 >= 窗口毫秒) {
        表.set(键, { 起点: 现在, 次数: 1 });
        return true;
      }
      if (记.次数 >= 上限) return false;
      记.次数 += 1;
      return true;
    },
    大小() {
      return 表.size;
    },
  };
}

/* ===== 路由（worker 与 dev-server 共用） ===== */

export function 跨域头(env = {}) {
  // GitHub Pages 是纯静态站，来源不固定；这里不带凭证，所以允许设成 *（执行指令 §10.2）。
  return {
    "access-control-allow-origin": env.ALLOWED_ORIGIN || "*",
    "access-control-allow-methods": "POST, OPTIONS",
    "access-control-allow-headers": "content-type",
    "access-control-max-age": "86400",
    vary: "Origin",
  };
}

/**
 * 同一个路由表，worker.js 与 dev-server.mjs 都走这里。
 * @returns {{状态码:number, 对象:object, 日志:object}}
 */
export async function 路由({
  method,
  pathname,
  bodyText = "",
  env = {},
  clientIp = "unknown",
  limiter = null,
  fetchImpl = fetch,
  logger = null,
}) {
  const 上限 = {
    ...默认上限,
    每分钟请求数:
      Number(env.RATE_LIMIT_PER_MINUTE) > 0
        ? Number(env.RATE_LIMIT_PER_MINUTE)
        : 默认上限.每分钟请求数,
  };

  let 结果;
  if (method === "GET" && (pathname === "/health" || pathname === "/")) {
    结果 = {
      状态码: 200,
      对象: {
        状态: "正常",
        服务: "LuCDA 出口（Cloudflare Workers 形态）",
        契约: "schema/annotation.schema.json",
        模型: {
          文字: 取模型名("text", env),
          图片: 取模型名("image", env),
          默认: 默认模型,
        },
        语音: {
          状态: "未实现",
          说明: "真实语音识别为后续开发；接口保留 audio 分支，但不返回转写结果。",
        },
        限流: {
          上限: 上限.每分钟请求数,
          窗口秒: Math.round(上限.限流窗口毫秒 / 1000),
        },
        密钥: {
          已从环境变量读取: Boolean(
            env.DEEPSEEK_API_KEY && String(env.DEEPSEEK_API_KEY).trim(),
          ),
        },
      },
      日志: { 结果: "健康检查" },
    };
  } else if (method === "POST" && pathname === "/api/analyze") {
    if (bodyText.length > 上限.请求体字符) {
      结果 = {
        状态码: 413,
        对象: {
          状态: "拒绝",
          错误: {
            标记: "BODY_TOO_LARGE",
            说明: `请求体超过 ${上限.请求体字符} 字符。`,
          },
        },
        日志: { 结果: "BODY_TOO_LARGE" },
      };
    } else {
      let body = null;
      let 解析错 = null;
      try {
        body = JSON.parse(bodyText);
      } catch (e) {
        解析错 = String(e?.message || e);
      }
      结果 = 解析错
        ? {
            状态码: 400,
            对象: {
              状态: "拒绝",
              错误: {
                标记: "BAD_JSON",
                说明: `请求体不是合法 JSON：${解析错}`,
              },
            },
            日志: { 结果: "BAD_JSON" },
          }
        : await 分析请求({ body, env, clientIp, limiter, fetchImpl });
    }
  } else {
    结果 = {
      状态码: 404,
      对象: {
        状态: "未找到",
        说明: "本服务只有 POST /api/analyze 与 GET /health。",
      },
      日志: { 结果: "404" },
    };
  }

  if (logger) logger(结果.日志);
  return 结果;
}

/* ===== Cloudflare Workers 入口 ===== */

const 全局限流器 = 造限流器();

export default {
  async fetch(request, env) {
    const 头 = 跨域头(env || {});
    try {
      if (request.method === "OPTIONS")
        return new Response(null, { status: 204, headers: 头 });

      const 方法 = request.method === "GET" ? "GET" : "POST";
      let pathname = "/";
      try {
        pathname = new URL(request.url).pathname;
      } catch {
        pathname = "/";
      }
      const bodyText = 方法 === "POST" ? await request.text() : "";
      const clientIp =
        request.headers.get("cf-connecting-ip") ||
        request.headers.get("x-forwarded-for") ||
        "unknown";

      const r = await 路由({
        method: 方法,
        pathname,
        bodyText,
        env: env || {},
        clientIp,
        limiter: 全局限流器,
        // 日志只记模态、长度、校验结果，不记用户输入（隐私）
        logger: (记) => console.log(JSON.stringify({ ...记, 来源: "worker" })),
      });

      return new Response(JSON.stringify(r.对象), {
        status: r.状态码,
        headers: { ...头, "content-type": "application/json; charset=utf-8" },
      });
    } catch (e) {
      // 兜底：任何未预期错误也只回一个不带判定的降级对象，不吞成 200（§2 铁律 13）
      return new Response(
        JSON.stringify({
          状态: "降级",
          错误: {
            标记: "WORKER_INTERNAL_ERROR",
            说明: `出口内部错误：${String(e?.message || e)}`,
          },
          判定: null,
          策略: null,
          溯源: [],
          提示: "出口出错，本次没有判定。可以改用离线演示样例。",
        }),
        {
          status: 500,
          headers: { ...头, "content-type": "application/json; charset=utf-8" },
        },
      );
    }
  },
};


function 降级对象({
  模态,
  标记,
  说明,
  上游状态,
  校验错误,
  原始返回片段,
  修复次数,
}) {
  return {
    状态: "降级",
    错误: {
      标记,
      说明,
      上游状态: 上游状态 === undefined ? null : 上游状态,
      校验错误: Array.isArray(校验错误) ? 校验错误.slice(0, 30) : [],
      原始返回片段:
        typeof 原始返回片段 === "string" ? 原始返回片段.slice(0, 2000) : "",
      修复次数: 修复次数 || 0,
    },
    meta: { 模态, 证据单位: 证据单位[模态] },
    判定: null, // 关键：降级时不下判定，绝不用「绿」冒充结论（§9.4、§2 铁律 13）
    策略: null,
    溯源: [],
    提示: "这次没有通过契约校验，所以不给判定。可以再发一次，或改用离线演示样例。",
  };
}


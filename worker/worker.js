export function 查策略形态(对象) {
  const 问题 = [];
  const 策略 = 对象?.策略;
  if (!策略 || !Array.isArray(策略.输出)) return 问题;
  const 输出 = 策略.输出;
  const 形态 = 输出.map((o) => o?.形态);
  const 有 = (x) => 形态.includes(x);

  const 该出 = {
    老人本人: "一句话",
    当事人: "问题",
    子女: "脚本",
    社区工作者: "脚本",
  }[策略.用户];
  if (该出 && 输出.some((o) => o?.形态 !== 该出))
    问题.push(
      `策略.用户 = ${策略.用户} 时，输出形态应全为「${该出}」（§4.2），实际是 ${[...new Set(形态)].join("/") || "空"}`,
    );

  if (有("问题")) {
    const 问 = 输出.filter((o) => o?.形态 === "问题");
    if (问.length !== 6)
      问题.push(`「问题」形态应为 6 条按序（§9.1），实际 ${问.length} 条`);
    if (问.some((o) => !Number.isInteger(o?.序号)))
      问题.push("「问题」形态每条都要写 序号（§9.1）");
    if (问.some((o) => !o?.他可能怎么答 || !o?.你再问))
      问题.push("每条问题后都要挂「他可能怎么答」与「你再问」（§9.1）");
    const 超长 = 问.filter((o) => 字数(o?.内容) > 15).map((o) => o?.内容);
    if (超长.length)
      问题.push(`每条问题 ≤15 字（§9.1），超长：${超长.join("；")}`);
  }

  if (有("脚本")) {
    const 段 = 输出.filter((o) => o?.形态 === "脚本").map((o) => o?.内容);
    const 缺 = 段名.filter((名, i) => !头里有段名(段[i], 名));
    if (段.length < 4 || 缺.length)
      问题.push(
        `「脚本」形态应给 4 条，按序以「开口：」「弹药：」「反驳预判：」「给台阶：」开头，第三、四条不能省（§9.2）；实际 ${段.length} 条，缺或错序：${缺.join("、") || "无"}`,
      );
  }

  if (有("一句话")) {
    const 超长 = 输出
      .filter((o) => o?.形态 === "一句话" && 字数(o?.内容) > 12)
      .map((o) => o?.内容);
    if (超长.length)
      问题.push(`「一句话」形态每条 ≤12 字（§9.3），超长：${超长.join("；")}`);
  }

  if (策略.对抗者 === "广告" && 有("问题"))
    问题.push("对抗者 = 广告 无交涉对象，不得输出问题清单（§4.3、§12）");

  return 问题;
}


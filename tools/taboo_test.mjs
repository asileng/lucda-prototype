/* 1. 10 条预置用例 */

console.log("\n--- 10 条预置用例 ---");
const 未命中 = [];
const 覆盖成因 = new Set();
const 覆盖类别 = new Set();
let 命中数 = 0;

for (const c of 用例) {
  const r = taboos.scan(c.文本, { 用户: c.用户, 对抗者: c.对抗者 });
  const 成因集 = r.命中.map((h) => h.成因);
  const 成因命中 = !!c.期望成因 && 成因集.some((x) => x.includes(c.期望成因));
  const 有命中 = r.命中.length >= 1;
  const 字段齐 = r.命中.every((h) => h.片段 && h.规则 && h.类别 && h.成因);

  if (有命中) {
    命中数++;
    for (const h of r.命中) {
      覆盖成因.add(h.成因);
      覆盖类别.add(h.类别);
    }
  } else {
    未命中.push(c.编号);
  }

  const 标记 = 有命中 && 成因命中 && 字段齐 ? "命中" : "未命中";
  console.log(
    `[${c.编号}] ${标记} ｜ 命中 ${r.命中.length} 个 ｜ 用户=${c.用户} 对抗者=${c.对抗者}` +
      ` ｜ 期望成因=${c.期望成因}${c.改写型 ? "（改写型）" : ""} ｜ ${c.说明}`,
  );
  for (const h of r.命中) {
    console.log(
      `        · 「${h.片段}」 类别=${h.类别} 成因=${h.成因} 规则=${h.规则}`,
    );
  }

  断言(有命中, `${c.编号} 未命中任何禁忌点`);
  断言(
    成因命中,
    `${c.编号} 未命中期望成因「${c.期望成因}」，实际 ${JSON.stringify(成因集)}`,
  );
  断言(字段齐, `${c.编号} 命中的字段不齐（片段/规则/类别/成因）`);
  断言(r.扫描.上下文完整, `${c.编号} 上下文未完整传入`);
}

const 命中率 = (命中数 / 用例.length) * 100;

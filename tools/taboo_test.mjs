  if (!row.用户 || !row.对抗者) 表格问题.push(`${row.编号} 缺 用户/对抗者`);
  if (!row.成因) 表格问题.push(`${row.编号} 缺 成因`);
  const 有字面 = (row.绝不能说 || []).length > 0;
  const 有句式 = (row.句式规则 || []).length > 0;
  const 声明不可判 = row.可正则化 === false;
  if (!有字面 && !有句式 && !声明不可判)
    表格问题.push(`${row.编号} 既无字面串也无句式规则，且未声明不可正则化`);

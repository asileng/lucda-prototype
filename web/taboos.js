  function blocked(text, start, end, m) {
    var i, p;
    for (i = 0; i < m.notBefore.length; i++) {
      p = m.notBefore[i];
      if (text.slice(Math.max(0, start - p.length), start) === p) return true;
    }
    for (i = 0; i < m.notAfter.length; i++) {
      p = m.notAfter[i];
      if (text.slice(end, end + p.length) === p) return true;
    }
    return false;
  }

  function matchLiteral(text, m) {
    var out = [];
    var re = new RegExp(m.body, m.flags);
    var r;
    while ((r = re.exec(text)) !== null) {
      if (r[0] === "") {
        re.lastIndex++;
        continue;
      }
      var start = r.index;
      var end = start + r[0].length;
      if (!blocked(text, start, end, m))
        out.push({ start: start, end: end, text: r[0] });
      if (!re.global) break;
    }
    return out;
  }

  function sentenceSpan(text, pos) {
    var enders = "。！？\n";
    var s = 0;
    for (var i = pos - 1; i >= 0; i--) {
      if (enders.indexOf(text.charAt(i)) >= 0) {
        s = i + 1;
        break;
      }
    }
    var e = text.length;
    for (var j = pos; j < text.length; j++) {
      if (enders.indexOf(text.charAt(j)) >= 0) {
        e = j + 1;
        break;
      }
    }
    return [s, e];
  }

  function sentenceContains(text, pos, word) {
    var sp = sentenceSpan(text, pos);
    return text.slice(sp[0], sp[1]).indexOf(word) >= 0;
  }


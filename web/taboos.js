  function escapeRe(s) {
    return String(s).replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
  }

  function stripSpace(s) {
    return String(s === null || s === undefined ? "" : s).replace(/\s+/g, "");
  }

  /* ---------- 编译：把规则数据变成可直接跑的匹配器 ---------- */

  function compileLiteral(word, calibers) {
    var w = stripSpace(word);
    var cal = (calibers && calibers[word]) || {};
    return {
      word: word,
      body: w.split("").map(escapeRe).join("\\s*"),
      flags: /[A-Za-z]/.test(w) ? "gi" : "g",
      notBefore: cal.排除前缀 || [],
      notAfter: cal.排除后缀 || [],
      cause: cal.成因 || "",
    };
  }

  function compile(rules) {
    var calibers = rules.词表匹配口径 || {};
    var causes = rules.通用禁用语成因 || {};
    var out = { 词表: [], 句式: [], 组合: [], 改写表: {}, 未覆盖: [] };
    var cats = rules.通用禁用语 || {};
    var cat, i, list;

    for (cat in cats) {
      if (!has(cats, cat)) continue;
      list = cats[cat] || [];
      for (i = 0; i < list.length; i++) {
        var matcher = compileLiteral(list[i], calibers);
        out.词表.push({
          类别: "通用禁用语·" + cat,
          规则: cat + "：" + list[i],
          成因: matcher.cause || causes[cat] || cat,
          优先级: 3,
          matcher: matcher,
        });
      }
    }

    var sentRules = (rules.句式规则 && rules.句式规则.行) || [];
    for (i = 0; i < sentRules.length; i++) {
      var s = sentRules[i];
      out.句式.push({
        编号: s.编号,
        正则: new RegExp(s.模式, "g"),
        说明: s.说明 || "",
        成因: s.成因 || "",
        生效条件: s.生效条件 || {},
        必须不含: s.必须不含 || [],
        处理: s.处理 || "删句",
        改写: s.改写 || "",
        来源: s.来源 || "",
        关联: s.关联组合禁忌 || [],
        模式: s.模式,
      });
    }

    var rows = (rules.组合禁忌 && rules.组合禁忌.行) || [];
    for (i = 0; i < rows.length; i++) {
      var row = rows[i];
      var lits = row.绝不能说 || [];
      var litsOut = [];
      for (var j = 0; j < lits.length; j++) {
        litsOut.push({
          word: lits[j],
          matcher: compileLiteral(lits[j], calibers),
        });
      }
      out.组合.push({ row: row, 字面串: litsOut });
      if (!lits.length && !(row.句式规则 || []).length)
        out.未覆盖.push(row.编号);
    }

    var rw = rules.改写建议 || [];
    for (i = 0; i < rw.length; i++) out.改写表[rw[i].命中] = rw[i];
    return out;
  }


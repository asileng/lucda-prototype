/** 模型有时会套 markdown 围栏，这里剥掉。只做剥壳，不改内容。 */
export function 取JSON文本(正文) {
  let s = String(正文 || "").trim();
  if (s.startsWith("```")) {
    s = s.replace(/^```[a-zA-Z]*\s*/, "");
    const 尾 = s.lastIndexOf("```");
    if (尾 >= 0) s = s.slice(0, 尾);
    s = s.trim();
  }
  if (s.startsWith("{")) return s;
  const 首 = s.indexOf("{");
  const 末 = s.lastIndexOf("}");
  return 首 >= 0 && 末 > 首 ? s.slice(首, 末 + 1) : s;
}


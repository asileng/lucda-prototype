/* 0. 内置兜底副本与 data/taboos.json 必须一致 */

function canon(v) {
  if (Array.isArray(v)) return v.map(canon);
  if (v && typeof v === "object") {
    const out = {};
    for (const k of Object.keys(v).sort()) out[k] = canon(v[k]);
    return out;
  }
  return v;
}

const 一致 =
  JSON.stringify(canon(taboos.内置规则)) === JSON.stringify(canon(RULES));
console.log(
  `\n[0] 内置兜底副本 vs data/taboos.json：${一致 ? "一致" : "不一致"}` +
    `（组合禁忌 ${RULES.组合禁忌.行.length} 格 / 句式规则 ${RULES.句式规则.行.length} 条 / 改写建议 ${RULES.改写建议.length} 条）`,
);

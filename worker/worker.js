/** 只判断请求本身是否可处理，不判断内容真假（§1.3）。 */
export function 检查请求(body, 上限 = 默认上限) {
  if (body === null || typeof body !== "object" || Array.isArray(body)) {
    return {
      通过: false,
      状态码: 400,
      标记: "BAD_BODY",
      说明: "请求体必须是一个 JSON 对象 {模态, 内容}。",
    };
  }
  const 模态 = typeof body.模态 === "string" ? body.模态.trim() : "";
  if (!模态取值.includes(模态)) {
    return {
      通过: false,
      状态码: 400,
      标记: "BAD_MODALITY",
      说明: "模态 只能填 text / image / audio。",
    };
  }
  if (typeof body.内容 !== "string" || body.内容.trim() === "") {
    return {
      通过: false,
      状态码: 400,
      标记: "EMPTY_CONTENT",
      说明: "内容 不能为空。",
      模态,
    };
  }
  const 内容 = body.内容;

  if (模态 === "text") {
    if (内容.length > 上限.文本字数) {
      return {
        通过: false,
        状态码: 400,
        标记: "TEXT_TOO_LONG",
        说明: `文字最多 ${上限.文本字数} 字，这次 ${内容.length} 字。`,
        模态,
      };
    }
    return { 通过: true, 模态, 内容 };
  }

  if (模态 === "image") {
    if (!图片前缀.test(内容)) {
      return {
        通过: false,
        状态码: 400,
        标记: "BAD_IMAGE",
        说明: "image 的内容要传 data URL，形如 data:image/png;base64,……",
        模态,
      };
    }
    const 载荷 = 内容.slice(内容.indexOf(",") + 1).replace(/\s+/g, "");
    const 字节 = Math.floor((载荷.length * 3) / 4);
    if (字节 > 上限.图片字节) {
      return {
        通过: false,
        状态码: 413,
        标记: "IMAGE_TOO_LARGE",
        说明: `图片解码后约 ${Math.round(字节 / 1024)} KB，超过上限 ${Math.round(上限.图片字节 / 1024)} KB。`,
        模态,
      };
    }
    return { 通过: true, 模态, 内容 };
  }

  // audio：不做真实语音识别（用户 2026-10-01 决定把 ASR 放到未来开发）。
  // 两条路：
  //   ① 没声明转写来源 → 直接返回「未实现」，绝不编一份转写出来；
  //   ② 调用方自带转写文本（如人工转写）并声明了来源 → 按语音模态分析这段文本，
  //      时间轴、重复次数等语音独占观察照常填（§7.2、§6.4）。
  // 本服务从不生成转写结果，只接受已经存在的转写文本。
  if (模态 === "audio") {
    const 转写来源 =
      typeof body.转写来源 === "string" ? body.转写来源.trim() : "";
    if (!转写来源) {
      return {
        通过: false,
        状态码: 501,
        标记: "AUDIO_NOT_IMPLEMENTED",
        说明: "语音识别为后续开发，本次不做，也不返回转写结果。要分析语音，请在 转写来源 里声明自带转写文本的来源（如「人工转写」）。",
        模态,
      };
    }
    if (内容.length > 上限.文本字数) {
      return {
        通过: false,
        状态码: 400,
        标记: "TEXT_TOO_LONG",
        说明: `转写文本最多 ${上限.文本字数} 字，这次 ${内容.length} 字。`,
        模态,
      };
    }
    return { 通过: true, 模态, 内容, 转写来源 };
  }
}


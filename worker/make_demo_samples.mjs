function 取片段(证据, 模态, 输入内容) {
  if (typeof 证据 === "string") {
    const s = 证据.trim();
    if (模态 === "text") {
      const m = /^(\d+)\s*-\s*(\d+)$/.exec(s);
      return m
        ? { 位置: s, 片段: 输入内容.slice(Number(m[1]), Number(m[2])) }
        : { 位置: s, 片段: "" };
    }
    if (模态 === "audio") {
      const m = /^([\d.]+)\s*-\s*([\d.]+)$/.exec(s);
      if (m) {
        const 行 = 输入内容.split("\n").find((l) => l.startsWith(`[${s}]`));
        return { 位置: s, 片段: 行 ? 行.slice(s.length + 3).trim() : "" };
      }
      return { 位置: s, 片段: "" };
    }
    return { 位置: s, 片段: "" };
  }
  if (证据 && typeof 证据 === "object") {
    return {
      位置: 证据.位置 || "",
      片段: 证据.片段 || "",
      观察: Array.isArray(证据.观察) ? 证据.观察 : [],
    };
  }
  return null;
}

function 抽锚点(结果, 输入) {
  const 色 = 结果.判定.风险;
  const 锚点 = [];
  const 模态 = 结果.meta.模态;
  const 短 = (s, n = 20) =>
    typeof s === "string" && s.length > n ? `${s.slice(0, n)}…` : s || "";

  (结果.事件层 || []).forEach((项, i) => {
    const f = 取片段(项.证据, 模态, 输入.内容);
    if (!f) return;
    锚点.push({
      片段: f.片段 || 短(f.位置),
      位置: f.位置,
      色,
      标签: `事件层 · ${项.语用目标}`,
      说话人: 项.说话人,
      来源字段: `事件层[${i}]`,
      观察: f.观察 || [],
    });
  });
  (结果.话语层 || []).forEach((项, i) => {
    const f = 取片段(项.证据, 模态, 输入.内容);
    if (!f) return;
    锚点.push({
      片段: f.片段 || 短(f.位置),
      位置: f.位置,
      色,
      标签: `话语层 · ${项.维度}：${短(项.值, 24)}`,
      说话人: 项.说话人,
      来源字段: `话语层[${i}]`,
      观察: f.观察 || [],
    });
  });
  (结果.说服杠杆层 || []).forEach((项, i) => {
    const f = 取片段(项.证据, 模态, 输入.内容);
    if (!f) return;
    锚点.push({
      片段: f.片段 || 短(f.位置),
      位置: f.位置,
      色,
      标签: `说服杠杆层 · ${项.杠杆} · 强度 ${项.强度} · ${项.归属}`,
      说话人: 项.说话人,
      来源字段: `说服杠杆层[${i}]`,
      观察: f.观察 || [],
    });
  });

  // 文本模态按字符起点排序；其它模态保持结果里的顺序
  if (模态 === "text") {
    锚点.sort(
      (a, b) =>
        (Number.parseInt(a.位置, 10) || 0) - (Number.parseInt(b.位置, 10) || 0),
    );
  }
  return 锚点;
}

/* ===== 禁忌扫描：只扫「要送达用户的叙述字段」 =====
 * 不扫 证据（那是把用户自己的话原样引回去）、不扫 策略.禁忌（那一栏按设计就是写着「绝不能说」的字面串）。
 * 命中的字段按 §5.5 走扫描 → 重写 → 再扫；整句被删空而导致该条标签不完整的，
 * 按「降级为不含该段的安全输出」把这条标签去掉，并把 原文 / 重写后 / 命中了什么 全部记下来。 */
function 扫描并改写(结果) {
  const ctx = 上下文(结果);
  const 记录 = [];
  const 目标 = [];
  const 加 = (字段, 容器, 键) => {
    if (typeof 容器?.[键] === "string") {
      目标.push({ 字段, 取: () => 容器[键], 存: (v) => (容器[键] = v) });
    }
  };

  加("判定.一句话", 结果.判定, "一句话");
  加("判定.触发规则", 结果.判定, "触发规则");
  加("判定.正常说法对照", 结果.判定, "正常说法对照");
  加("诊断.被说到哪一步", 结果.诊断, "被说到哪一步");
  加("诊断.依据", 结果.诊断, "依据");
  加("策略.语域", 结果.策略, "语域");
  (结果.策略.输出 || []).forEach((项, i) => {
    for (const k of ["内容", "他可能怎么答", "你再问"])
      加(`策略.输出[${i}].${k}`, 项, k);
  });
  (结果.事件层 || []).forEach((项, i) => {
    for (const k of ["人物关系", "语用目标"]) 加(`事件层[${i}].${k}`, 项, k);
  });
  (结果.话语层 || []).forEach((项, i) => 加(`话语层[${i}].值`, 项, "值"));
  (结果.溯源 || []).forEach((项, i) => {
    for (const k of ["断言", "语料例证"]) 加(`溯源[${i}].${k}`, 项, k);
  });

  for (const t of 目标) {
    const 原文 = t.取();
    if (typeof 原文 !== "string" || !原文.trim()) continue;
    const r = taboos.enforce(原文, ctx);
    if (r.状态 === "放行") continue;
    记录.push({
      字段: t.字段,
      原文,
      重写后: r.文本,
      处理: r.状态,
      命中: r.命中.map((h) => ({
        片段: h.片段,
        规则: h.规则,
        类别: h.类别,
        成因: h.成因 || "",
        处理动作: h.处理 || "",
      })),
      动作: r.记录,
    });
    t.存(r.文本);
  }

  // 降级：整句被删空后，这条标签就不完整了 —— 去掉这条标签，并记下被去掉的原文
  const 去掉 = (数组名, 必填键) => {
    const 原 = 结果[数组名] || [];
    const 留下 = 原.filter(
      (项) => typeof 项?.[必填键] === "string" && 项[必填键].trim() !== "",
    );
    if (留下.length !== 原.length) {
      记录.push({
        字段: 数组名,
        处理: "降级",
        说明: `重写后有 ${原.length - 留下.length} 条标签的 ${必填键} 被删空，已去掉这些条目`,
        去掉的条目: 原
          .filter((项) => !留下.includes(项))
          .map((項) => JSON.stringify(項).slice(0, 200)),
        命中: [],
        动作: [],
      });
      结果[数组名] = 留下;
    }
  };
  去掉("溯源", "断言");
  去掉("话语层", "值");
  去掉("事件层", "语用目标");

  return { 上下文: ctx, 命中条数: 记录.length, 记录 };
}

